import type { FoodAssessment } from '../domain/schemas'

type Condition = {
  kind: 'preparation' | 'storage' | 'serving' | 'frequency' | 'composition' | 'other'
  instruction: string
}

type AssessmentSpec = {
  foodIds: string[]
  statusId: 'pregnancy-ok' | 'pregnancy-conditions' | 'pregnancy-avoid'
  summary: string
  locator: string
  instruction?: string
  conditions?: Condition[]
}

